#!/usr/bin/env python3
"""Check the RPCs the CLI calls against the extracted schema.

  check_rpcs.py            # report; exit 1 if a used RPC disappeared
  check_rpcs.py --write    # also regenerate schema/used.proto

Used RPCs are found by scanning src/ for `{SVC}/Method` and `FooService/Method` strings.
`schema/used.proto` holds just those RPCs plus every message/enum they reach, so after
re-running extract_schema.py a `git diff schema/used.proto` shows only the changes that
can affect this CLI (docs/schema.md describes the whole update procedure).
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROTO = os.path.join(ROOT, "schema/aiserver.proto")
DEFAULT_SVC = "GrokBotService"  # value of api::SVC


def used_rpcs():
    found = set()
    for dirpath, _, files in os.walk(os.path.join(ROOT, "src")):
        for f in files:
            if f.endswith(".rs"):
                src = open(os.path.join(dirpath, f)).read()
                for svc, m in re.findall(r'(\{SVC\}|[A-Z]\w*Service)/([A-Z]\w+)', src):
                    found.add((DEFAULT_SVC if svc == "{SVC}" else svc, m))
    return sorted(found)


def parse_proto(text):
    """Top-level blocks by name, plus rpc signatures per service."""
    blocks, rpcs = {}, {}
    for m in re.finditer(r'^(message|enum|service) (\w+) \{\n(.*?)^\}\n', text, re.S | re.M):
        kind, name, body = m.groups()
        blocks[name] = m.group(0)
        if kind == "service":
            for r, req, res in re.findall(r'rpc (\w+)\((?:stream )?(\w+)\) returns \((?:stream )?(\w+)\)', body):
                rpcs[(name, r)] = (req, res)
    return blocks, rpcs


def closure(blocks, roots):
    seen, todo = [], list(roots)
    while todo:
        n = todo.pop()
        if n in seen or n not in blocks:
            continue
        seen.append(n)
        for ref in re.findall(r'\b([A-Z]\w*)\b', blocks[n].split("{", 1)[1]):
            todo.append(ref)
    return sorted(seen)


def main():
    text = open(PROTO).read()
    version = re.search(r'from Grok Bot (\S+)', text).group(1)
    blocks, rpcs = parse_proto(text)
    used = used_rpcs()
    missing = [u for u in used if u not in rpcs]
    for svc, m in used:
        sig = rpcs.get((svc, m))
        print(f"{'ok     ' if sig else 'MISSING'} {svc}/{m}" + (f"  ({sig[0]} -> {sig[1]})" if sig else ""))
    if "--write" in sys.argv:
        roots = [t for u in used if u in rpcs for t in rpcs[u]]
        out = [
            f"// GENERATED by tools/check_rpcs.py from schema/aiserver.proto (Grok Bot {version}).",
            "// Only the RPCs this CLI calls and the types they reach. Review `git diff` of this",
            "// file after updating the schema.",
            "",
        ]
        by_svc = {}
        for svc, m in used:
            if (svc, m) in rpcs:
                by_svc.setdefault(svc, []).append((m, *rpcs[(svc, m)]))
        for svc, ms in sorted(by_svc.items()):
            out.append(f"service {svc} {{")
            out += [f"  rpc {m}({i}) returns ({o});" for m, i, o in ms]
            out += ["}", ""]
        for n in closure(blocks, roots):
            out.append(blocks[n])
        with open(os.path.join(ROOT, "schema/used.proto"), "w") as f:
            f.write("\n".join(out))
        print(f"wrote schema/used.proto ({len(used) - len(missing)} rpcs)", file=sys.stderr)
    if missing:
        print(f"\n{len(missing)} RPC(s) used by the CLI are gone from Grok Bot {version}!", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
